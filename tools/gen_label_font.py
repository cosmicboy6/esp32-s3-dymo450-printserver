#!/usr/bin/env python3
"""Generate dymo_label_font.h: 1-bit glyph tables for the label form.

The web form on the print server renders up to four lines of text into the
LabelWriter's ESC/P raster stream. The glyphs are pre-rendered from
DejaVuSans-Bold (the same font used for the test label) so the firmware needs
no font file and no TTF rasteriser at runtime.

Run from the repository root:

    python3 tools/gen_label_font.py

Output: external_components/dymo_printserver/dymo_label_font.h
"""

from __future__ import annotations

import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

FONT_FILE = Path(
    "/home/opencode/workspace/.tmp/browser/chr/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
)

# Printable ASCII plus Latin-1 supplement (covers German umlauts / sharp s).
CODEPOINTS = list(range(32, 127)) + list(range(160, 256))

# name -> pixel size
SIZES = {"BIG": 56, "SMALL": 38}

OUT = Path(__file__).resolve().parent.parent / "external_components/dymo_printserver/dymo_label_font.h"


def render_font(font: ImageFont.FreeTypeFont):
    ascent, descent = font.getmetrics()
    glyphs = []
    blob = bytearray()
    for cp in CODEPOINTS:
        ch = chr(cp)
        adv = int(round(font.getlength(ch)))
        left, top, right, bottom = font.getbbox(ch, anchor="ls")
        w = max(0, right - left)
        h = max(0, bottom - top)
        off = len(blob)
        if w > 0 and h > 0:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-left, -top), ch, font=font, fill=255, anchor="ls")
            px = img.load()
            stride = (w + 7) // 8
            for y in range(h):
                row = bytearray(stride)
                for x in range(w):
                    if px[x, y] >= 128:
                        row[x >> 3] |= 0x80 >> (x & 7)
                blob += row
        glyphs.append((adv, w, h, left, top, off))
    return ascent, descent, glyphs, bytes(blob)


def c_bytes(data: bytes) -> str:
    out = []
    for i in range(0, len(data), 16):
        out.append("  " + ", ".join(f"0x{b:02X}" for b in data[i : i + 16]) + ",")
    return "\n".join(out)


def main() -> int:
    if not FONT_FILE.exists():
        print(f"font not found: {FONT_FILE}", file=sys.stderr)
        return 1

    parts = [
        "// Generated by tools/gen_label_font.py - do not edit by hand.",
        "// 1-bit glyphs rendered from DejaVuSans-Bold for the label web form.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace esphome::dymo_printserver {",
        "",
        "struct LabelGlyph {",
        "  uint8_t adv;    // pen advance in pixels",
        "  uint8_t w;      // bitmap width",
        "  uint8_t h;      // bitmap height",
        "  int8_t left;    // bitmap x offset from the pen position",
        "  int8_t top;     // bitmap y offset from the baseline (negative = above)",
        "  uint16_t off;   // offset into the bitmap blob",
        "};",
        "",
        "struct LabelFont {",
        "  int16_t ascent;   // distance from the ascender line down to the baseline",
        "  int16_t descent;  // distance from the baseline down to the descender line",
        "  const uint8_t *index;      // 256 entries: glyph slot for a codepoint, 0xFF = none",
        "  const LabelGlyph *glyphs;  // slots, indexed via index[]",
        "  const uint8_t *bits;       // packed 1-bit bitmaps, MSB = leftmost pixel",
        "};",
        "",
    ]

    for name, size in SIZES.items():
        font = ImageFont.truetype(str(FONT_FILE), size)
        ascent, descent, glyphs, blob = render_font(font)
        index = bytearray([0xFF] * 256)
        for i, cp in enumerate(CODEPOINTS):
            index[cp] = i
        print(f"{name}: size={size} ascent={ascent} descent={descent} glyphs={len(glyphs)} blob={len(blob)}B")
        parts.append(f"static const uint8_t LABEL_FONT_{name}_INDEX[256] = {{")
        parts.append("  " + ", ".join(f"0x{b:02X}" for b in index) + ",")
        parts.append("};")
        parts.append("")
        parts.append(f"static const LabelGlyph LABEL_FONT_{name}_GLYPHS[{len(glyphs)}] = {{")
        for adv, w, h, left, top, off in glyphs:
            parts.append(f"  {{{adv}, {w}, {h}, {left}, {top}, {off}}},")
        parts.append("};")
        parts.append("")
        parts.append(f"static const uint8_t LABEL_FONT_{name}_BITS[{len(blob)}] = {{")
        parts.append(c_bytes(blob))
        parts.append("};")
        parts.append("")
        parts.append(
            f"static const LabelFont LABEL_FONT_{name} = {{"
            f"{ascent}, {descent}, LABEL_FONT_{name}_INDEX, LABEL_FONT_{name}_GLYPHS, LABEL_FONT_{name}_BITS}};"
        )
        parts.append("")

    parts.append("}  // namespace esphome::dymo_printserver")
    parts.append("")

    OUT.write_text("\n".join(parts))
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
